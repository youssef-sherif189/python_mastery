age = 18
country = "EGY"
Rank = 10
print(age > 17)
print(age > 11 and country == "EGY" and Rank == 10)
print(age > 18 and country == "KSA" and Rank == 10)
print(age > 18 and country == "EGY" and Rank == 99)

print(age > 28 or country == "EGY" or Rank == 20)
print(age > 17 or country == "KSA" or Rank == 20)

print(age > 17) # True
print(not age > 17) # Not True # False
